/**
 * Generates the Android launcher icon, splash icon and Play Store icon from the
 * feather in site/public/favicon.svg, matching the iOS icon
 * (scripts/generate-ios-assets.mjs).
 *
 * - drawable/ic_launcher_{background,foreground,monochrome}.xml: the adaptive
 *   icon layers (mipmap-anydpi-v26). The feather sits inside the 66 dp safe
 *   circle of the 108 dp canvas; monochrome is what Android 13+ tints for
 *   themed icons.
 * - drawable/splash_icon.xml: the same feather in @color/splash_icon, for the
 *   Android 12+ splash screen (light and dark via values-night).
 * - mipmap-<density>/ic_launcher{,_round}.png: legacy icons for API 24-25.
 * - src-tauri/android/play-icon-512.png: the Play Store listing icon.
 *
 * Not a dependency. Re-run (Node 20+) from the repo root:
 *   npm i --prefix /tmp/android-sharp sharp && NODE_PATH=/tmp/android-sharp/node_modules node scripts/generate-android-assets.mjs
 */
import { createRequire } from 'node:module';
import fs from 'node:fs';

const require = createRequire(import.meta.url);
const sharp = require(require.resolve('sharp', { paths: [process.env.NODE_PATH ?? '.'] }));

const RES = 'src-tauri/gen/android/app/src/main/res';
const d = fs.readFileSync('site/public/favicon.svg', 'utf8').match(/<path[^>]*\sd="([^"]+)"/)[1];

// The 64-unit favicon centred on the 108-unit adaptive canvas at 0.75: the
// feather's farthest point is 31 units from the centre, inside the 33 safe zone.
const SCALE = 0.75;
const OFFSET = 54 - 32 * SCALE;
const LIGHT = ['#FAF8F1', '#F2ECDC'];
const INK = '#67665E';

const vector = (body) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-android-assets.mjs -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
${body}
</vector>
`;
const feather = (fill) => `    <group android:translateX="${OFFSET}" android:translateY="${OFFSET}"
        android:scaleX="${SCALE}" android:scaleY="${SCALE}">
        <path android:fillType="evenOdd" android:fillColor="${fill}"
            android:pathData="${d}" />
    </group>`;

const DRAWABLES = {
  'ic_launcher_background.xml': `    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="0" android:startY="0"
                android:endX="108" android:endY="108"
                android:startColor="${LIGHT[0]}" android:endColor="${LIGHT[1]}" />
        </aapt:attr>
    </path>`,
  'ic_launcher_foreground.xml': feather(INK),
  'ic_launcher_monochrome.xml': feather('#FF000000'),
  'splash_icon.xml': feather('@color/splash_icon'),
};
for (const [file, body] of Object.entries(DRAWABLES)) {
  fs.writeFileSync(`${RES}/drawable/${file}`, vector(body));
}

// PNGs show the 72-unit visible part of the canvas, clipped to `shape`.
const png = (shape) =>
  Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72" width="1024" height="1024">
  <defs>
    <linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${LIGHT[0]}"/><stop offset="1" stop-color="${LIGHT[1]}"/></linearGradient>
    <clipPath id="c">${shape}</clipPath>
  </defs>
  <g clip-path="url(#c)">
    <rect x="18" y="18" width="72" height="72" fill="url(#g)"/>
    <path fill-rule="evenodd" fill="${INK}" transform="translate(${OFFSET} ${OFFSET}) scale(${SCALE})" d="${d}"/>
  </g>
</svg>`);
const SQUARE = '<rect x="18" y="18" width="72" height="72"/>';
const ROUNDED = '<rect x="18" y="18" width="72" height="72" rx="16"/>';
const CIRCLE = '<circle cx="54" cy="54" r="36"/>';

const DENSITIES = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };
for (const [density, size] of Object.entries(DENSITIES)) {
  for (const [file, shape] of [['ic_launcher.png', ROUNDED], ['ic_launcher_round.png', CIRCLE]]) {
    await sharp(png(shape)).resize(size, size).png({ compressionLevel: 9 }).toFile(`${RES}/mipmap-${density}/${file}`);
  }
}

// Play applies its own mask, so the listing icon is a full-bleed square.
fs.mkdirSync('src-tauri/android', { recursive: true });
await sharp(png(SQUARE)).resize(512, 512).flatten().png({ compressionLevel: 9 }).toFile('src-tauri/android/play-icon-512.png');
